(* RW.8 behavior review: two checked versions of a callable compared over declared finite cases
   (docs/behavior-review.md). *)

let ( let* ) = Result.bind

(* --- diagnostics --- *)

let summary = function
  | "E1010" -> "A behavior review's program or cases file is invalid"
  | "E1011" -> "The two versions' entry contracts differ"
  | "E1012" -> "A behavior review's domain, field or world is invalid"
  | "E1013" -> "The two versions' review domains differ"
  | "E1014" -> "The observation policy cannot apply to both versions"
  | "E1015" -> "A behavior review's sampling options are invalid"
  | code -> raise (Diag.Bug_invalid_diagnostic ("unknown behavior review code " ^ code))

let next_step = function
  | "E1010" ->
      "Make each version check together with the cases file, and keep the cases file to new \
       declarations only."
  | "E1011" -> "Compare entries with one signature and call labels, or name an --adapter."
  | "E1012" ->
      "Declare each domain as a finite List or Distribution of the parameter's type, keep fields \
       and handlers pure, and --handle every operation the entry performs."
  | "E1013" -> "Declare the same domain values in both versions, over unchanged types."
  | "E1014" -> "List only operations both versions declare, and do not pin an interface."
  | "E1015" ->
      "Pass --sample N with --seed S, sample only Distribution domains, keep N within --max-cases."
  | code -> raise (Diag.Bug_invalid_diagnostic ("unknown behavior review code " ^ code))

let diagnostic ~code cause =
  Diag.error ~domain:Diag.Warp ~code ~summary:(summary code) ~cause ~next_step:(next_step code)
    ~contrast:None ()

let refuse ~code fmt = Printf.ksprintf (fun cause -> Error [ diagnostic ~code cause ]) fmt

(* --- request --- *)

type options = {
  prelude_dir : string;
  old_file : string;
  old_source : string;
  new_file : string;
  new_source : string;
  cases_file : string;
  cases_source : string;
  entry : string;
  domains : string list;
  fields : string list;
  adapter : string option;
  handles : (string * string) list;
  wrap : string option;
  policy : Observation_policy.t;
  fuel : int;
  max_cases : int;
  sample : (int * int) option;  (** count, seed *)
  only_case : int option;
}

type domain_kind = List_domain | Distribution_domain
type side = Old | New

let side_name = function Old -> "old" | New -> "new"

(* --- assembly: version, cases file, generated driver --- *)

let driver_prefix = "review-driver-"

(* a, b, ..., z, aa, ab, ...: identifier-safe suffixes *)
let letters index =
  let rec go n acc =
    let acc = String.make 1 (Char.chr (Char.code 'a' + (n mod 26))) ^ acc in
    if n < 26 then acc else go ((n / 26) - 1) acc
  in
  go index ""

let param index = "x-" ^ letters index

type operation_info = { op_name : string; arity : int }

let target options side =
  match (side, options.adapter) with New, Some adapter -> adapter | _ -> options.entry

let generate_driver options side ~kinds ~operations =
  let n = List.length options.domains in
  let params = List.init n param in
  let args = String.concat ", " params in
  let buf = Buffer.create 1024 in
  let add fmt = Printf.ksprintf (Buffer.add_string buf) fmt in
  add "\n-- generated by jacquard review\n";
  let target = target options side in
  (match options.wrap with
  | Some wrap -> add "%scase(%s) = %s(fn () -> %s(%s))\n" driver_prefix args wrap target args
  | None -> add "%scase(%s) = %s(%s)\n" driver_prefix args target args);
  add "%slist-elem(xs, x) = match xs { | Nil -> x | Cons(y, _) -> y }\n" driver_prefix;
  add "%sdist-elem(d, x) = match d { | Categorical(Cons(MkPair(y, _), _)) -> y | _ -> x }\n"
    driver_prefix;
  let typing body =
    let lets =
      List.mapi
        (fun k (domain, kind) ->
          Printf.sprintf "  let _ = %s%s(%s, %s)\n" driver_prefix
            (match kind with List_domain -> "list-elem" | Distribution_domain -> "dist-elem")
            domain (param k))
        (List.combine options.domains kinds)
    in
    Printf.sprintf "(%s) = {\n%s  %s\n}\n" args (String.concat "" lets) body
  in
  (* the static world: the case under a handler for exactly the modeled operations; its row must
     be empty, so the entry needs no effect the review does not model *)
  (match operations with
  | [] -> add "%sworld(thunk) = thunk()\n" driver_prefix
  | ops ->
      add "%sworld(thunk) =\n  handle thunk() {\n    | return v -> v\n" driver_prefix;
      List.iteri
        (fun i ({ op_name; arity }, (_, term)) ->
          let ps = List.init arity (fun j -> Printf.sprintf "p-%s-%s" (letters i) (letters j)) in
          let ps = String.concat ", " ps in
          add "    | %s(%s) resume k -> k(%s(%s))\n" op_name ps term ps)
        (List.combine ops options.handles);
      add "  }\n");
  add "%styping%s" driver_prefix
    (typing (Printf.sprintf "%sworld(fn () -> %scase(%s))" driver_prefix driver_prefix args));
  List.iteri
    (fun j field ->
      add "%sfield-%s%s" driver_prefix (letters j) (typing (Printf.sprintf "%s(%s)" field args)))
    options.fields;
  Buffer.contents buf

type checked_version = {
  root : string;
  artifact : Frontend.Checked.t;
  store : Store.t;
  checker : Check.ctx;
}

let rec remove_tree path =
  if Sys.is_directory path then (
    Array.iter (fun f -> remove_tree (Filename.concat path f)) (Sys.readdir path);
    Sys.rmdir path)
  else Sys.remove path

(* private scratch stores, created under TMPDIR and removed at exit *)
let fresh_root () =
  let dir = Filename.temp_dir ~perms:0o700 "jacquard-review-" ".store" in
  at_exit (fun () -> try remove_tree dir with Sys_error _ -> ());
  dir

let store_failure error =
  Error
    [
      diagnostic ~code:"E1010"
        (Printf.sprintf "the review could not prepare its private store: %s"
           (Printexc.to_string error));
    ]

let check_source_unguarded ~prelude_dir ~file source =
  let root = fresh_root () in
  match Frontend.check ~prelude_dir ~root ~syntax:Frontend.Auto ~file source with
  | Error diagnostics -> Error diagnostics
  | Ok (Frontend.Recovered { diagnostics; _ }) -> Error diagnostics
  | Ok (Frontend.Checked artifact) ->
      let* store = Store.open_store root in
      let* checker = Frontend.make_checker store in
      Ok { root; artifact; store; checker }

let check_source ~prelude_dir ~file source =
  try check_source_unguarded ~prelude_dir ~file source
  with (Sys_error _ | Unix.Unix_error _) as error -> store_failure error

let wrap_e1010 side diagnostics =
  Error
    (diagnostic ~code:"E1010"
       (Printf.sprintf "the %s version does not check together with the cases file" (side_name side))
    :: diagnostics)

let introduced (top : Frontend.Checked.top) = List.map fst top.signatures

let export_of version name =
  Interface.find (Frontend.Checked.interface version.artifact) name Resolve.KTerm

let term_hash side version name =
  match export_of version name with
  | Some export -> Ok export.Interface.hash
  | None -> refuse ~code:"E1010" "the %s version has no term named `%s`" (side_name side) name

let prelude_type store name =
  match Prelude_identity.lookup_kind store name Resolve.KType with
  | Some { Resolve.hash; _ } -> Some hash
  | None -> None

let scheme_head checker hash =
  match Types.repr (Check.term_scheme checker hash).Types.ty with
  | Types.TCon (head, _) -> Some head
  | _ -> None

let arrow_row_empty checker hash =
  match Types.repr (Check.term_scheme checker hash).Types.ty with
  | Types.TArrow (_, row, _) -> (Types.repr_row row).Types.effects = []
  | _ -> true

let operation_arity checker op =
  match Check.force_operation checker op with
  | Ok { Check.scheme; _ } -> (
      match Types.repr scheme.Types.ty with
      | Types.TArrow (ps, _, _) -> Some (List.length ps)
      | _ -> None)
  | Error _ -> None

let lookup_operation store name =
  match Prelude_identity.lookup_kind store name Resolve.KOp with
  | Some { Resolve.hash; _ } -> Some hash
  | None -> None

(* --- entry contract --- *)

let labels_encoding = function
  | None -> "positional"
  | Some slots -> String.concat "," (List.map (function Some l -> l | None -> "_") slots)

let entry_contract side version name =
  match export_of version name with
  | None -> refuse ~code:"E1010" "the %s version has no term named `%s`" (side_name side) name
  | Some export ->
      let signature = Option.value export.Interface.signature ~default:"" in
      let labels = labels_encoding export.Interface.labels in
      let identity =
        Hash.of_string (String.concat "\000" [ "jacquard-behavior-entry-v1"; signature; labels ])
      in
      Ok (signature, labels, identity)

(* phase 1: the version alone; phase 2: version + cases; phase 3: + the generated driver *)
let prepare_version options side =
  let file, source =
    match side with
    | Old -> (options.old_file, options.old_source)
    | New -> (options.new_file, options.new_source)
  in
  let* alone =
    match check_source ~prelude_dir:options.prelude_dir ~file source with
    | Ok v -> Ok v
    | Error diagnostics ->
        Error
          (diagnostic ~code:"E1010"
             (Printf.sprintf "the %s version does not check" (side_name side))
          :: diagnostics)
  in
  let version_tops = Frontend.Checked.tops alone.artifact in
  let version_names = List.concat_map introduced version_tops in
  let assembled = source ^ "\n" ^ options.cases_source in
  let assembled_file = file ^ "+" ^ Filename.basename options.cases_file in
  let* with_cases =
    match check_source ~prelude_dir:options.prelude_dir ~file:assembled_file assembled with
    | Ok v -> Ok v
    | Error diagnostics -> wrap_e1010 side diagnostics
  in
  let cases_tops =
    List.filteri
      (fun i _ -> i >= List.length version_tops)
      (Frontend.Checked.tops with_cases.artifact)
  in
  let* () =
    match
      List.find_map
        (fun (top : Frontend.Checked.top) ->
          match top.resolved with
          | Kernel.Expr _ -> Some "the cases file has a top-level expression"
          | Kernel.Decl _ ->
              List.find_map
                (fun name ->
                  if List.mem name version_names || String.starts_with ~prefix:driver_prefix name
                  then Some (Printf.sprintf "the cases file redeclares `%s`" name)
                  else None)
                (introduced top))
        cases_tops
    with
    | Some cause -> refuse ~code:"E1010" "%s (%s version)" cause (side_name side)
    | None -> Ok ()
  in
  (* domain kinds and modeled operations, from the phase 2 schemes *)
  let list_type = prelude_type with_cases.store "list" in
  let dist_type = prelude_type with_cases.store "distribution" in
  let* kinds =
    List.fold_right
      (fun name acc ->
        let* acc = acc in
        let* hash = term_hash side with_cases name in
        match scheme_head with_cases.checker hash with
        | Some head when Some head = list_type -> Ok (List_domain :: acc)
        | Some head when Some head = dist_type -> Ok (Distribution_domain :: acc)
        | _ -> refuse ~code:"E1012" "domain `%s` is neither a List nor a Distribution" name)
      options.domains (Ok [])
  in
  let* operations =
    List.fold_right
      (fun (op_name, term) acc ->
        let* acc = acc in
        match lookup_operation with_cases.store op_name with
        | None -> refuse ~code:"E1012" "--handle names `%s`, which is not an operation" op_name
        | Some op -> (
            let* term_h = term_hash side with_cases term in
            if not (arrow_row_empty with_cases.checker term_h) then
              refuse ~code:"E1012" "handler term `%s` performs effects; it must be pure" term
            else
              match operation_arity with_cases.checker op with
              | Some arity -> Ok ({ op_name; arity } :: acc)
              | None -> refuse ~code:"E1012" "operation `%s` has no checked signature" op_name))
      options.handles (Ok [])
  in
  let* contract = entry_contract side with_cases (target options side) in
  let finish () =
    let driver = generate_driver options side ~kinds ~operations in
    let* final =
      match
        check_source ~prelude_dir:options.prelude_dir ~file:assembled_file (assembled ^ driver)
      with
      | Ok v -> Ok v
      | Error diagnostics ->
          Error
            (diagnostic ~code:"E1012"
               (Printf.sprintf
                  "the %s version's domains, fields, handlers or wrap do not fit the entry's \
                   parameters"
                  (side_name side))
            :: diagnostics)
    in
    let* typing = term_hash side final (driver_prefix ^ "typing") in
    let* () =
      if arrow_row_empty final.checker typing then Ok ()
      else
        refuse ~code:"E1012"
          "missing world configuration: the %s entry performs effects that no --handle models"
          (side_name side)
    in
    let* () =
      List.fold_left
        (fun acc j ->
          let* () = acc in
          let* h = term_hash side final (driver_prefix ^ "field-" ^ letters j) in
          if arrow_row_empty final.checker h then Ok ()
          else
            refuse ~code:"E1012" "field `%s` performs effects; it must be pure"
              (List.nth options.fields j))
        (Ok ())
        (List.init (List.length options.fields) Fun.id)
    in
    Ok (final, kinds)
  in
  Ok (contract, finish)

(* --- domains --- *)

let run_term ctx hash = Eval.run_expr ctx Kernel.{ it = Ref (hash, Term); meta = Meta.empty }
let runtime_cause error = Diag.to_string (Runtime_err.to_diag error)

let rec list_values = function
  | Value.VCon { name = "cons"; args = [ x; rest ]; _ } ->
      Result.map (fun xs -> x :: xs) (list_values rest)
  | Value.VCon { name = "nil"; args = []; _ } -> Ok []
  | v -> Error (Printf.sprintf "%s is not a list" (Value.display v))

(* domain values are declared data: Int, Real, Text, constructors (Bool and lists included) and
   tuples; anything else (secrets, closures, hashes, code, ...) is refused *)
let rec unsupported_kind = function
  | Observation.Int _ | Observation.Real _ | Observation.Text _ -> None
  | Observation.Tuple items -> List.find_map unsupported_kind items
  | Observation.Constructor { arguments; _ } -> List.find_map unsupported_kind arguments
  | Observation.Hash _ -> Some "hash"
  | Observation.Code _ -> Some "code"
  | Observation.Opaque kind -> Some kind

let data_of value =
  let observed = Observation.of_value value in
  match unsupported_kind observed with
  | Some kind -> Error kind
  | None -> Ok (observed, Observation_transcript.render_data observed)

type element = {
  value : Value.t;
  observed : Observation.value;
  data : string;
  weight : float option;
}

(* a distribution's support: equal values merged at their first position, zero weights dropped *)
let merge_support elements =
  let merged =
    List.fold_left
      (fun acc e ->
        if List.exists (fun x -> String.equal x.data e.data) acc then
          List.map
            (fun x ->
              if String.equal x.data e.data then
                { x with weight = Some (Option.get x.weight +. Option.get e.weight) }
              else x)
            acc
        else acc @ [ e ])
      [] elements
  in
  List.filter (fun e -> Option.get e.weight > 0.) merged

let domain_elements ctx kind name value =
  let raw =
    match kind with
    | List_domain -> Result.map (List.map (fun v -> (v, None))) (list_values value)
    | Distribution_domain -> (
        match Infer_dist.dist_of_value ctx value with
        | Error error -> Error (runtime_cause error)
        | Ok d -> (
            match Infer_dist.support ctx d with
            | Error error -> Error (runtime_cause error)
            | Ok entries ->
                let total = List.fold_left (fun acc (_, w) -> acc +. w) 0. entries in
                if
                  List.exists
                    (fun (_, w) -> Float.is_nan w || w < 0. || not (Float.is_finite w))
                    entries
                  || (not (Float.is_finite total))
                  || total <= 0.
                then Error "its weights are not finite and non-negative with a positive total"
                else Ok (List.map (fun (v, w) -> (v, Some w)) entries)))
  in
  match raw with
  | Error cause -> refuse ~code:"E1012" "domain `%s`: %s" name cause
  | Ok [] -> refuse ~code:"E1012" "domain `%s` is empty" name
  | Ok raw -> (
      let rec render acc = function
        | [] -> Ok (List.rev acc)
        | (value, weight) :: rest -> (
            match data_of value with
            | Error kind ->
                refuse ~code:"E1012" "domain `%s` contains an unsupported %s value" name kind
            | Ok (observed, data) -> render ({ value; observed; data; weight } :: acc) rest)
      in
      let* rendered = render [] raw in
      match kind with
      | List_domain -> Ok rendered
      | Distribution_domain -> (
          match merge_support rendered with
          | [] -> refuse ~code:"E1012" "domain `%s` has no value of positive weight" name
          | kept -> Ok kept))

(* --- evaluation context --- *)

type prepared = {
  version : checked_version;
  ctx : Eval.ctx;
  case_fn : Value.t;
  field_fns : Value.t list;
  handler_fns : (Hash.t * Value.t) list;
  domain_values : element list list;
  contract : string * string * Hash.t;
  entry_hash : Hash.t;
  domain_hashes : Hash.t list;
  field_hashes : Hash.t list;
  handle_hashes : (Hash.t * Hash.t) list;
  wrap_hash : Hash.t option;
  interface_identity : Hash.t;
}

let evaluate options side (version, kinds) =
  let* _store, ctx =
    try Frontend.open_session ~prelude_dir:options.prelude_dir ~root:version.root
    with (Sys_error _ | Unix.Unix_error _) as error -> store_failure error
  in
  let* entry_hash = term_hash side version (target options side) in
  let* contract = entry_contract side version (target options side) in
  let* domain_hashes =
    List.fold_right
      (fun name acc ->
        let* acc = acc in
        let* h = term_hash side version name in
        Ok (h :: acc))
      options.domains (Ok [])
  in
  let* field_hashes =
    List.fold_right
      (fun name acc ->
        let* acc = acc in
        let* h = term_hash side version name in
        Ok (h :: acc))
      options.fields (Ok [])
  in
  let* handle_hashes =
    List.fold_right
      (fun (op, term) acc ->
        let* acc = acc in
        match lookup_operation version.store op with
        | None -> refuse ~code:"E1012" "--handle names `%s`, which is not an operation" op
        | Some op_h ->
            let* t = term_hash side version term in
            Ok ((op_h, t) :: acc))
      options.handles (Ok [])
  in
  let* wrap_hash =
    match options.wrap with
    | None -> Ok None
    | Some w -> Result.map Option.some (term_hash side version w)
  in
  let* case_h = term_hash side version (driver_prefix ^ "case") in
  let* field_driver_hs =
    List.fold_right
      (fun j acc ->
        let* acc = acc in
        let* h = term_hash side version (driver_prefix ^ "field-" ^ letters j) in
        Ok (h :: acc))
      (List.init (List.length options.fields) Fun.id)
      (Ok [])
  in
  (* the preparation invocation: domain values and term values, no root handler *)
  let prepared =
    Eval.with_invocation ~coverage:false ~fuel:options.fuel ctx @@ fun _ ->
    let value_of h =
      match run_term ctx h with
      | Ok v -> Ok v
      | Error error ->
          refuse ~code:"E1012" "preparing the %s version failed: %s" (side_name side)
            (runtime_cause error)
    in
    let* case_fn = value_of case_h in
    let* field_fns =
      List.fold_right
        (fun h acc ->
          let* acc = acc in
          let* v = value_of h in
          Ok (v :: acc))
        field_driver_hs (Ok [])
    in
    let* handler_fns =
      List.fold_right
        (fun (op, t) acc ->
          let* acc = acc in
          let* v = value_of t in
          Ok ((op, v) :: acc))
        handle_hashes (Ok [])
    in
    let* domain_values =
      List.fold_right
        (fun ((name, kind), h) acc ->
          let* acc = acc in
          let* v = value_of h in
          let* elements = domain_elements ctx kind name v in
          Ok (elements :: acc))
        (List.combine (List.combine options.domains kinds) domain_hashes)
        (Ok [])
    in
    Ok (case_fn, field_fns, handler_fns, domain_values)
  in
  let* case_fn, field_fns, handler_fns, domain_values = prepared in
  Ok
    {
      version;
      ctx;
      case_fn;
      field_fns;
      handler_fns;
      domain_values;
      contract;
      entry_hash;
      domain_hashes;
      field_hashes;
      handle_hashes;
      wrap_hash;
      interface_identity = Interface.identity (Frontend.Checked.interface version.artifact);
    }

(* --- cases --- *)

type mode = Exhaustive | Sampled of { count : int; seed : int }

let product_cap = 1_000_000

(* case [index]'s element index per parameter: the first parameter outermost *)
let decode sizes index =
  let rec go acc index = function
    | [] -> acc
    | size :: rest -> go ((index mod size) :: acc) (index / size) rest
  in
  go [] index (List.rev sizes)

let domains_equal (olds : element list list) (news : element list list) =
  List.length olds = List.length news
  && List.for_all2
       (fun a b ->
         List.length a = List.length b
         && List.for_all2 (fun x y -> String.equal x.data y.data && x.weight = y.weight) a b)
       olds news

(* sampled cases: root [Rng.make seed]; stream k is the (k+1)-th [Rng.split root]; case i's value
   for parameter k is the (i+1)-th [Infer_dist.draw] from stream k over domain k's support *)
let sample_indices domains ~count ~seed =
  let root = Infer_dist.Rng.make seed in
  let streams = List.map (fun _ -> Infer_dist.Rng.split root) domains in
  let indexed = List.map (List.mapi (fun i e -> (i, Option.value e.weight ~default:1.))) domains in
  let per_param =
    List.map2
      (fun stream entries ->
        let entries = List.map (fun (i, w) -> (Value.VInt i, w)) entries in
        Array.init count (fun _ ->
            match Infer_dist.draw stream entries with Value.VInt i -> i | _ -> 0))
      streams indexed
  in
  List.init count (fun i -> List.map (fun draws -> draws.(i)) per_param)

(* --- running --- *)

type run_state = Complete_run | Failed_run of string | Incomplete_run | Not_started

let state_name = function
  | Complete_run -> "complete"
  | Failed_run code -> "failed:" ^ code
  | Incomplete_run -> "incomplete"
  | Not_started -> "not-started"

type run = { state : run_state; transcript : Observation_transcript.transcript option }

let run_cases options (p : prepared) (cases : int list list) =
  Eval.with_invocation ~coverage:false ~fuel:options.fuel p.ctx @@ fun _ ->
  List.iter
    (fun (op, handler) ->
      Eval.register_root_handler p.ctx op (fun args -> Eval.call p.ctx handler args))
    p.handler_fns;
  let stopped = ref false in
  List.map
    (fun indices ->
      if !stopped then { state = Not_started; transcript = None }
      else
        let args =
          List.map2 (fun elements i -> (List.nth elements i).value) p.domain_values indices
        in
        let recorder = Observation_transcript.create options.policy in
        ignore
          (Observation_transcript.record recorder p.ctx (fun () -> Eval.call p.ctx p.case_fn args));
        let transcript = Observation_transcript.transcript recorder in
        let state =
          match Observation_transcript.runs transcript with
          | [ { Observation_transcript.status = Complete _; _ } ] -> Complete_run
          | [ { status = Failed code; _ } ] -> Failed_run code
          | _ ->
              stopped := true;
              Incomplete_run
        in
        { state; transcript = Some transcript })
    cases

(* --- verdicts --- *)

type kind = Decision | Effect | Failure_kind

let kind_name = function Decision -> "decision" | Effect -> "effect" | Failure_kind -> "failure"

type verdict = Agree | Differ of kind | Inconclusive | Both_failed | Unrun

let verdict_name = function
  | Agree -> "agree"
  | Differ _ -> "differ"
  | Inconclusive -> "inconclusive"
  | Both_failed -> "failed"
  | Unrun -> "unrun"

let kind_of_position = function
  | Observation_transcript.Run_position _ | Status_position _ | Value_position _ -> Decision
  | Event_position _ | Operation_position _ | Argument_position _ | Result_position _
  | Output_position _ ->
      Effect

let pair_verdict old_run new_run =
  match (old_run.state, new_run.state) with
  | (Incomplete_run | Not_started), _ | _, (Incomplete_run | Not_started) -> Unrun
  | Failed_run _, Failed_run _ -> Both_failed
  | Failed_run _, _ | _, Failed_run _ -> Differ Failure_kind
  | Complete_run, Complete_run -> (
      match
        Observation_transcript.compare (Option.get old_run.transcript)
          (Option.get new_run.transcript)
      with
      | Ok Observation_transcript.Equal -> Agree
      | Ok (Divergent { position; _ }) -> Differ (kind_of_position position)
      | Ok (Inconclusive _) | Error _ -> Inconclusive)

(* --- grouping (exact conjunctions) --- *)

type atom = { path : string; head : string }

let rec value_atoms path (v : Observation.value) =
  let head, children =
    match v with
    | Observation.Constructor { identity; name; arguments } ->
        (name ^ "#" ^ Hash.to_hex identity, arguments)
    | Observation.Tuple items -> (Printf.sprintf "tuple/%d" (List.length items), items)
    | other -> (Observation_transcript.render_data other, [])
  in
  { path; head }
  :: List.concat (List.mapi (fun i c -> value_atoms (Printf.sprintf "%s.%d" path i) c) children)

type group = {
  group_kind : kind;
  members : int list;  (** case numbers, ascending *)
  condition : [ `Atoms of atom list | `All | `Ungrouped ];
}

let groups ~atoms_of ~verdicts =
  let agreeing = List.filter_map (fun (i, v) -> if v = Agree then Some i else None) verdicts in
  let satisfies case atoms = List.for_all (fun a -> List.mem a (atoms_of case)) atoms in
  let excludes atoms = not (List.exists (fun c -> satisfies c atoms) agreeing) in
  List.filter_map
    (fun kind ->
      let members =
        List.filter_map (fun (i, v) -> if v = Differ kind then Some i else None) verdicts
      in
      match members with
      | [] -> None
      | first :: rest ->
          let shared =
            List.filter
              (fun a -> List.for_all (fun c -> List.mem a (atoms_of c)) rest)
              (atoms_of first)
          in
          let condition =
            if not (excludes shared) then `Ungrouped
            else
              let kept =
                List.fold_left
                  (fun kept a ->
                    let without = List.filter (fun b -> b <> a) kept in
                    if excludes without then without else kept)
                  shared shared
              in
              if kept = [] then `All else `Atoms kept
          in
          Some { group_kind = kind; members; condition })
    [ Decision; Effect; Failure_kind ]

(* --- request and report --- *)

type review = {
  request : string;
  request_identity : Hash.t;
  status : string;
  mode : mode;
  sizes : int list;
  cases : int list list;  (** element indices per case, in case order *)
  case_numbers : int list;  (** each case's number (its position) *)
  old_runs : run list;
  new_runs : run list;
  verdicts : verdict list;
  groups : group list;
  domains : element list list;
  options : options;
  only_case : bool;
}

let hex = Hash.to_hex

let request_bytes options ~(old_p : prepared) ~(new_p : prepared) ~kinds ~mode =
  let buf = Buffer.create 1024 in
  let line fmt =
    Printf.ksprintf
      (fun s ->
        Buffer.add_string buf s;
        Buffer.add_char buf '\n')
      fmt
  in
  let prelude_identity (p : prepared) =
    match Frontend.Checked.prelude p.version.artifact with
    | None -> "none"
    | Some pairs ->
        hex (Hash.of_string (String.concat "\n" (List.map (fun (k, v) -> k ^ "=" ^ v) pairs)))
  in
  let _, _, old_contract = old_p.contract and _, _, new_contract = new_p.contract in
  line "jacquard-behavior-review-request format=1";
  line "core version=%s prelude=%s" Version.version (prelude_identity old_p);
  line "old source=%s entry=%s contract=%s interface=%s"
    (hex (Hash.of_string options.old_source))
    (hex old_p.entry_hash) (hex old_contract) (hex old_p.interface_identity);
  line "new source=%s entry=%s contract=%s interface=%s adapter=%s"
    (hex (Hash.of_string options.new_source))
    (hex new_p.entry_hash) (hex new_contract) (hex new_p.interface_identity)
    (match options.adapter with None -> "none" | Some _ -> hex new_p.entry_hash);
  line "cases source=%s" (hex (Hash.of_string options.cases_source));
  List.iteri
    (fun k (kind, (o, n)) ->
      line "domain index=%d kind=%s old=%s new=%s" k
        (match kind with List_domain -> "list" | Distribution_domain -> "distribution")
        (hex o) (hex n))
    (List.combine kinds (List.combine old_p.domain_hashes new_p.domain_hashes));
  List.iteri
    (fun j (name, (o, n)) -> line "field index=%d name=%s old=%s new=%s" j name (hex o) (hex n))
    (List.combine options.fields (List.combine old_p.field_hashes new_p.field_hashes));
  List.iter
    (fun ((oo, ot), (no, nt)) ->
      line "handle op-old=%s op-new=%s term-old=%s term-new=%s" (hex oo) (hex no) (hex ot) (hex nt))
    (List.combine old_p.handle_hashes new_p.handle_hashes);
  line "wrap %s"
    (match (old_p.wrap_hash, new_p.wrap_hash) with
    | Some o, Some n -> hex o ^ ":" ^ hex n
    | _ -> "none");
  line "policy %s" (hex (Observation_policy.identity options.policy));
  line "budget fuel-model=%s fuel=%d max-cases=%d" Eval.fuel_model options.fuel options.max_cases;
  (match mode with
  | Exhaustive -> line "mode exhaustive"
  | Sampled { count; seed } -> line "mode sampled count=%d seed=%d" count seed);
  Buffer.contents buf

let request_identity bytes = Hash.of_string ("jacquard-behavior-review-request-v1\000" ^ bytes)

let counts review =
  let count p = List.length (List.filter p review.verdicts) in
  ( List.length review.verdicts,
    count (( = ) Agree),
    count (function Differ _ -> true | _ -> false),
    count (( = ) Inconclusive),
    count (( = ) Both_failed),
    count (( = ) Unrun) )

let review_status ~mode ~old_runs ~new_runs ~verdicts =
  let failed r = match r.state with Failed_run _ -> true | _ -> false in
  if List.exists failed old_runs || List.exists failed new_runs then "failed"
  else
    match mode with
    | Sampled _ -> "sampled"
    | Exhaustive ->
        if List.mem Unrun verdicts then "exhaustive-incomplete" else "exhaustive-complete"

let exit_status review =
  let _, _, differ, inconclusive, failed, unrun = counts review in
  if differ > 0 then 1 else if inconclusive + failed + unrun > 0 then 2 else 0

let framed buf keyword bytes =
  Buffer.add_string buf (Printf.sprintf "%s bytes=%d\n" keyword (String.length bytes));
  Buffer.add_string buf bytes;
  Buffer.add_char buf '\n'

let serialize review =
  let buf = Buffer.create 4096 in
  let line fmt =
    Printf.ksprintf
      (fun s ->
        Buffer.add_string buf s;
        Buffer.add_char buf '\n')
      fmt
  in
  line "jacquard-behavior-review-report format=1";
  framed buf "request" review.request;
  line "status %s mode %s" review.status
    (match review.mode with Exhaustive -> "exhaustive" | Sampled _ -> "sampled");
  let cases, agree, differ, inconclusive, failed, unrun = counts review in
  line "counts cases=%d agree=%d differ=%d inconclusive=%d failed=%d unrun=%d" cases agree differ
    inconclusive failed unrun;
  let case_at n =
    List.nth review.cases (List.length (List.filter (fun m -> m < n) review.case_numbers))
  in
  let run_at runs n =
    List.nth runs (List.length (List.filter (fun m -> m < n) review.case_numbers))
  in
  List.iteri
    (fun index g ->
      let first = List.hd g.members in
      (match g.condition with
      | `Atoms atoms ->
          line "group index=%d kind=%s cases=%d first=%d condition=%d" index
            (kind_name g.group_kind) (List.length g.members) first (List.length atoms);
          List.iter
            (fun a ->
              if String.starts_with ~prefix:"field=" a.path then
                framed buf
                  (Printf.sprintf "atom field=%s value"
                     (String.sub a.path 6 (String.length a.path - 6)))
                  a.head
              else framed buf (Printf.sprintf "atom path=%s value" a.path) a.head)
            atoms
      | `All ->
          line "group index=%d kind=%s cases=%d first=%d condition=all" index
            (kind_name g.group_kind) (List.length g.members) first
      | `Ungrouped ->
          line "group index=%d kind=%s cases=%d first=%d ungrouped" index (kind_name g.group_kind)
            (List.length g.members) first;
          List.iter (fun m -> line "member case=%d" m) g.members);
      line "witness case=%d" first;
      List.iteri
        (fun k i ->
          framed buf (Printf.sprintf "arg index=%d" k) (List.nth (List.nth review.domains k) i).data)
        (case_at first);
      let transcript runs =
        match (run_at runs first).transcript with
        | Some t -> Observation_transcript.serialize t
        | None -> ""
      in
      framed buf "old" (transcript review.old_runs);
      framed buf "new" (transcript review.new_runs))
    review.groups;
  (* every case that does not agree, with each version's run state; equal unrun runs compacted *)
  let rows =
    List.filter_map
      (fun (n, (v, (o, w))) -> if v = Agree then None else Some (n, v, o.state, w.state))
      (List.combine review.case_numbers
         (List.combine review.verdicts (List.combine review.old_runs review.new_runs)))
  in
  let rec emit = function
    | [] -> ()
    | (n, Unrun, o, w) :: rest ->
        let rec span last = function
          | (m, Unrun, o', w') :: more when m = last + 1 && o' = o && w' = w -> span m more
          | more -> (last, more)
        in
        let last, more = span n rest in
        if last = n then
          line "case index=%d verdict=unrun old=%s new=%s" n (state_name o) (state_name w)
        else
          line "case index=%d to=%d verdict=unrun old=%s new=%s" n last (state_name o)
            (state_name w);
        emit more
    | (n, v, o, w) :: rest ->
        line "case index=%d verdict=%s old=%s new=%s" n
          (match v with Differ k -> "differ:" ^ kind_name k | v -> verdict_name v)
          (state_name o) (state_name w);
        emit rest
  in
  emit rows;
  line "claims declared-support-only";
  Buffer.contents buf

(* --- the review --- *)

let is_operation store operation =
  match Store.locate_internal store operation with
  | Ok { Store.role = Store.Operation _; _ } -> true
  | Ok _ | Error _ -> false

let check_policy options (old_p : prepared) (new_p : prepared) =
  match Observation_policy.interface options.policy with
  | Some _ ->
      refuse ~code:"E1014"
        "the policy is pinned to an interface; a review compares two versions, whose manifests \
         differ"
  | None ->
      let in_both op = is_operation old_p.version.store op && is_operation new_p.version.store op in
      Result.map_error
        (fun diagnostics ->
          diagnostic ~code:"E1014" "the policy lists an operation that is not in both versions"
          :: diagnostics)
        (Observation_policy.validate_operations options.policy ~is_operation:in_both)

let field_values options (old_p : prepared) cases =
  Eval.with_invocation ~coverage:false ~fuel:options.fuel old_p.ctx @@ fun _ ->
  List.fold_right
    (fun indices acc ->
      let* acc = acc in
      let args =
        List.map2 (fun elements i -> (List.nth elements i).value) old_p.domain_values indices
      in
      let* values =
        List.fold_right
          (fun (name, fn) acc ->
            let* acc = acc in
            match Eval.call old_p.ctx fn args with
            | Error error -> refuse ~code:"E1012" "field `%s` failed: %s" name (runtime_cause error)
            | Ok v -> (
                match data_of v with
                | Error kind ->
                    refuse ~code:"E1012" "field `%s` returned an unsupported %s value" name kind
                | Ok (_, data) -> Ok ((name, data) :: acc)))
          (List.combine options.fields old_p.field_fns)
          (Ok [])
      in
      Ok (values :: acc))
    cases (Ok [])

let run options =
  let* () =
    match options.sample with
    | Some (count, _) when count < 1 || count > options.max_cases ->
        refuse ~code:"E1015" "--sample %d must be between 1 and --max-cases %d" count
          options.max_cases
    | _ -> Ok ()
  in
  let* () =
    if options.domains = [] then
      refuse ~code:"E1012" "the review needs one --domain per entry parameter"
    else Ok ()
  in
  let* old_contract, old_finish = prepare_version options Old in
  let* new_contract, new_finish = prepare_version options New in
  let* () =
    let os, ol, _ = old_contract and ns, nl, _ = new_contract in
    if String.equal os ns && String.equal ol nl then Ok ()
    else
      refuse ~code:"E1011" "the old entry has signature %s labels %s; the new %s has %s labels %s"
        os ol
        (match options.adapter with Some a -> "adapter `" ^ a ^ "`" | None -> "entry")
        ns nl
  in
  let* old_version, old_kinds = old_finish () in
  let* new_version, new_kinds = new_finish () in
  let* () =
    if old_kinds = new_kinds then Ok ()
    else refuse ~code:"E1013" "a domain is a List in one version and a Distribution in the other"
  in
  let kinds = old_kinds in
  let* () =
    match options.sample with
    | Some _ when List.mem List_domain kinds ->
        refuse ~code:"E1015" "--sample needs every domain to be a Distribution"
    | _ -> Ok ()
  in
  let* old_p = evaluate options Old (old_version, kinds) in
  let* new_p = evaluate options New (new_version, kinds) in
  let* () = check_policy options old_p new_p in
  let* () =
    if domains_equal old_p.domain_values new_p.domain_values then Ok ()
    else refuse ~code:"E1013" "the two versions' domain values differ"
  in
  let sizes = List.map List.length old_p.domain_values in
  let mode =
    match options.sample with Some (count, seed) -> Sampled { count; seed } | None -> Exhaustive
  in
  let* declared, numbered =
    match mode with
    | Sampled { count; seed } ->
        let cases = sample_indices old_p.domain_values ~count ~seed in
        Ok (cases, List.init count Fun.id)
    | Exhaustive ->
        let total =
          List.fold_left (fun acc n -> if acc > product_cap then acc else acc * n) 1 sizes
        in
        if total > product_cap then
          refuse ~code:"E1012" "the domains' product has more than %d cases" product_cap
        else Ok (List.init total (decode sizes), List.init total Fun.id)
  in
  let* selected =
    match options.only_case with
    | None -> Ok None
    | Some k when k >= 0 && k < List.length declared -> Ok (Some k)
    | Some k ->
        refuse ~code:"E1012" "--case %d is not a case of this review (%d cases)" k
          (List.length declared)
  in
  let cases, case_numbers =
    match selected with Some k -> ([ List.nth declared k ], [ k ]) | None -> (declared, numbered)
  in
  let budget = match selected with Some _ -> 1 | None -> options.max_cases in
  let runnable = List.filteri (fun i _ -> i < budget) cases in
  let pad runs =
    runs
    @ List.init
        (List.length cases - List.length runs)
        (fun _ -> { state = Not_started; transcript = None })
  in
  let old_runs = pad (run_cases options old_p runnable) in
  let new_runs = pad (run_cases options new_p runnable) in
  let verdicts = List.map2 pair_verdict old_runs new_runs in
  let analyzed =
    List.filter_map
      (fun ((indices, n), v) -> if v = Unrun then None else Some (n, indices))
      (List.combine (List.combine cases case_numbers) verdicts)
  in
  let* fields = field_values options old_p (List.map snd analyzed) in
  let field_table = List.combine (List.map fst analyzed) fields in
  let atoms_of n =
    let indices = List.nth cases (List.length (List.filter (fun m -> m < n) case_numbers)) in
    List.concat
      (List.mapi
         (fun k i ->
           value_atoms (Printf.sprintf "arg%d" k)
             (List.nth (List.nth old_p.domain_values k) i).observed)
         indices)
    @ List.map
        (fun (name, data) -> { path = "field=" ^ name; head = data })
        (Option.value (List.assoc_opt n field_table) ~default:[])
  in
  let groups = groups ~atoms_of ~verdicts:(List.combine case_numbers verdicts) in
  let request = request_bytes options ~old_p ~new_p ~kinds ~mode in
  Ok
    {
      request;
      request_identity = request_identity request;
      status = review_status ~mode ~old_runs ~new_runs ~verdicts;
      mode;
      sizes;
      cases;
      case_numbers;
      old_runs;
      new_runs;
      verdicts;
      groups;
      domains = old_p.domain_values;
      options;
      only_case = selected <> None;
    }

