(* the readable report shows display names: data-v1 identity qualifiers are dropped *)
let display data =
  let n = String.length data in
  let buf = Buffer.create n in
  let is_hex c = (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') in
  let rec go i =
    if i < n then
      if
        data.[i] = '#'
        && i + 64 < n + 1
        && i + 65 <= n
        && String.for_all is_hex (String.sub data (i + 1) 64)
      then go (i + 65)
      else (
        Buffer.add_char buf data.[i];
        go (i + 1))
  in
  go 0;
  Buffer.contents buf

let describe_run run =
  match (run.state, run.transcript) with
  | Complete_run, Some t -> (
      match Observation_transcript.runs t with
      | [ { status = Complete (Some (Observation_transcript.Data d)); events } ] ->
          Printf.sprintf "%s%s" (display d)
            (match List.length events with
            | 0 -> ""
            | 1 -> " (1 observed operation)"
            | k -> Printf.sprintf " (%d observed operations)" k)
      | [ { events; _ } ] -> Printf.sprintf "complete (%d observed operations)" (List.length events)
      | _ -> "complete")
  | state, _ -> state_name state

let render review =
  let buf = Buffer.create 2048 in
  let line fmt =
    Printf.ksprintf
      (fun s ->
        Buffer.add_string buf s;
        Buffer.add_char buf '\n')
      fmt
  in
  let total, agree, differ, inconclusive, failed, unrun = counts review in
  let declared = List.fold_left ( * ) 1 review.sizes in
  line "Behavior review %s" (hex review.request_identity);
  line "  old %s, new %s, entry %s%s" review.options.old_file review.options.new_file
    review.options.entry
    (match review.options.adapter with Some a -> " (adapter " ^ a ^ ")" | None -> "");
  line "  policy %s" (hex (Observation_policy.identity review.options.policy));
  let scope =
    match review.mode with
    | Sampled { count; seed } -> Printf.sprintf "in %d sampled cases (seed %d)" count seed
    | Exhaustive when review.only_case -> "on the one selected case"
    | Exhaustive -> Printf.sprintf "on the %d declared cases" declared
  in
  line "Status %s, %s." review.status scope;
  line "  %d run: %d agree, %d differ, %d inconclusive, %d failed in both, %d unrun."
    (total - unrun) agree differ inconclusive failed unrun;
  let case_word n =
    Printf.sprintf "case %d (%d of %d)" n (n + 1) (if review.only_case then declared else total)
  in
  let case_at n =
    List.nth review.cases (List.length (List.filter (fun m -> m < n) review.case_numbers))
  in
  List.iter
    (fun g ->
      line "";
      line "%d %s (%s):" (List.length g.members)
        (if List.length g.members = 1 then "case differs" else "cases differ")
        (kind_name g.group_kind);
      (match g.condition with
      | `Atoms atoms ->
          line "  when %s"
            (String.concat " and "
               (List.map
                  (fun a ->
                    if String.starts_with ~prefix:"field=" a.path then
                      String.sub a.path 6 (String.length a.path - 6) ^ " = " ^ display a.head
                    else a.path ^ " = " ^ display a.head)
                  atoms))
      | `All -> line "  in every analyzed case (no case agrees)"
      | `Ungrouped ->
          line
            "  ungrouped: no conjunction of declared fields separates them from the agreeing cases");
      let first = List.hd g.members in
      line "  witness %s: %s" (case_word first)
        (String.concat ", "
           (List.mapi
              (fun k i -> display (List.nth (List.nth review.domains k) i).data)
              (case_at first)));
      let run_at runs n =
        List.nth runs (List.length (List.filter (fun m -> m < n) review.case_numbers))
      in
      line "    old: %s" (describe_run (run_at review.old_runs first));
      line "    new: %s" (describe_run (run_at review.new_runs first)))
    review.groups;
  (match (differ, inconclusive, failed, unrun) with
  | 0, 0, 0, 0 ->
      line "";
      line "The versions agree %s." scope
  | _ -> ());
  line "";
  line "This review covers only the declared cases. It does not show that the versions are";
  line "equivalent anywhere else.";
  Buffer.contents buf
